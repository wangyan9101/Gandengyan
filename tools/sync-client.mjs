import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
let stale = false;
for (const name of ['rules', 'local']) {
  const source = path.join(root, 'packages', name, 'src');
  const output = path.join(root, 'assets', 'scripts', 'generated', name);
  const files = (await readdir(source)).filter((file) => file.endsWith('.ts'));
  if (!check) await mkdir(output, { recursive: true });
  for (const file of files) {
    const contents = await readFile(path.join(source, file), 'utf8');
    const expected = '// GENERATED by npm run client:sync. Edit packages/' + name + '/src instead.\n' +
      contents.replaceAll("'../../rules/src'", "'../rules/index'");
    const target = path.join(output, file);
    let current;
    try { current = await readFile(target, 'utf8'); } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (current !== expected) {
      if (check) { console.error(`Stale generated client module: ${path.relative(root, target)}`); stale = true; }
      else await writeFile(target, expected, 'utf8');
    }
  }
  let outputs = [];
  try { outputs = await readdir(output); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  for (const file of outputs.filter((file) => file.endsWith('.ts') && !files.includes(file))) {
    console.error(`Unexpected generated module: ${path.relative(root, path.join(output, file))}; remove via Creator if obsolete.`);
    stale = true;
  }
}
if (stale) process.exitCode = 1;
else console.log(check ? 'Client source mirrors match packages.' : 'Client source mirrors synchronized; .meta files untouched.');
